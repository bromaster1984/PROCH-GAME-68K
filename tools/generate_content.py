#!/usr/bin/env python3
"""Compile authored labels and an original small bitmap font. No runtime JSON."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
POLISH = 'ĄąĆćĘęŁłŃńÓóŚśŹźŻż'
NORMALIZE = str.maketrans({'„':'"', '”':'"', '“':'"', '’':"'", '‘':"'",
                          '—':'-', '–':'-', '…':'...', '\u00a0':' '})


def encode(text):
    result = bytearray()
    for char in text.translate(NORMALIZE):
        if 0x20 <= ord(char) <= 0x7e:
            result.append(ord(char))
        elif char in POLISH:
            result.append(0x80 + POLISH.index(char))
        elif char == '\n':
            result.append(10)
        else:
            raise ValueError(f'Unsupported game text character {char!r} U+{ord(char):04X}')
    return bytes(result)


def literal(text):
    return '"' + ''.join(f'\\{b:03o}' for b in encode(text)) + '"'


def glyphs():
    # Original pixel drawings, five columns; baseline row 8 in an eleven-row cell.
    patterns = '''
0:0e11131519110e 1:040c040404040e 2:0e11010204081f 3:1e01010e01011e
4:02060a121f0202 5:1f10101e01011e 6:0e10101e11110e 7:1f010204080808
8:0e11110e11110e 9:0e11110f01010e
A:0e11111f111111 B:1e11111e11111e C:0e11101010110e D:1e11111111111e
E:1f10101e10101f F:1f10101e101010 G:0e11101711110e H:1111111f111111
I:0e04040404040e J:0702020202120c K:11121418141211 L:1010101010101f
M:111b1515111111 N:11191513111111 O:0e11111111110e P:1e11111e101010
Q:0e11111115120d R:1e11111e141211 S:0f10100e01011e T:1f040404040404
U:1111111111110e V:11111111110a04 W:11111115151b11 X:11110a040a1111
Y:11110a04040404 Z:1f01020408101f
a:00000e010f110f b:1010161911111e c:00000e1010100e d:01010d1311110f
e:00000e111f100e f:0609091c080808 g:00000f11110f01 h:10101619111111
i:04000c0404040e j:02000602020202 k:10101214181412 l:0c04040404040e
m:00001a15151515 n:00001619111111 o:00000e1111110e p:00001e11111e10
q:00000f11110f01 r:00001619101010 s:00000f100e011e t:08081c08080906
u:0000111111130d v:00001111110a04 w:0000111115150a x:0000110a040a11
y:00001111110f01 z:00001f0204081f
'''
    result = {}
    for definition in patterns.split():
        char, digits = definition.split(':')
        result[char] = [0, 0] + list(bytes.fromhex(digits)) + [0, 0]
    punctuation = {
        ' ': [0]*7, '!':[4,4,4,4,4,0,4], '"':[10,10,10,0,0,0,0],
        '#':[10,31,10,10,31,10,0], '$':[4,15,20,14,5,30,4],
        '%':[17,2,4,4,8,16,17], '&':[12,18,20,8,21,18,13],
        "'": [4,4,8,0,0,0,0], '(':[2,4,8,8,8,4,2], ')':[8,4,2,2,2,4,8],
        '*':[0,21,14,31,14,21,0], '+':[0,4,4,31,4,4,0], ',':[0,0,0,0,0,4,8],
        '-':[0,0,0,31,0,0,0], '.':[0,0,0,0,0,0,4], '/':[1,2,2,4,8,8,16],
        ':':[0,4,0,0,4,0,0], ';':[0,4,0,0,4,4,8], '<':[2,4,8,16,8,4,2],
        '=':[0,0,31,0,31,0,0], '>':[8,4,2,1,2,4,8], '?':[14,17,1,2,4,0,4],
        '@':[14,17,23,21,23,16,14], '[':[14,8,8,8,8,8,14],
        '\\':[16,8,8,4,2,2,1], ']':[14,2,2,2,2,2,14], '^':[4,10,17,0,0,0,0],
        '_':[0,0,0,0,0,0,31], '`':[8,4,0,0,0,0,0], '{':[6,4,4,8,4,4,6],
        '|':[4,4,4,4,4,4,4], '}':[12,4,4,2,4,4,12], '~':[0,0,9,22,0,0,0]
    }
    result.update({c:[0,0]+rows+[0,0] for c,rows in punctuation.items()})
    for c, tail in {'g':[17,14], 'j':[18,12], 'p':[16,16], 'q':[1,1], 'y':[17,14]}.items():
        result[c][9:] = tail
    bases = 'AaCcEeLlNnOoSsZzZz'
    for c, base in zip(POLISH, bases):
        rows = result[base].copy()
        if c in 'ĄąĘę': rows[9:] = [2,1]
        elif c in 'Łł': rows[5] |= 6; rows[6] |= 24
        elif c in 'Żż': rows[0:2] = [4,0]
        else: rows[0:2] = [2,4]
        result[c] = rows
    chars = ''.join(chr(c) for c in range(32,127)) + POLISH
    assert set(chars) == set(result)
    assert all(len(v)==11 and all(0<=row<32 for row in v) for v in result.values())
    return chars, result


def generate(directory):
    directory = Path(directory); directory.mkdir(parents=True, exist_ok=True)
    chars, rows = glyphs()
    atlas = bytearray(12 * 88)  # 16 cells per row, 8 rows, width 96 pixels
    for index,c in enumerate(chars):
        ox,oy=(index%16)*6,(index//16)*11
        for y,row in enumerate(rows[c]):
            for x in range(5):
                if row & (16>>x):
                    px,py=ox+x,oy+y
                    atlas[py*12+px//8] |= 0x80 >> (px%8)
    font_header = '/* Original glyphs, generated by tools/generate_content.py. */\n'
    font_header += '#include <stdint.h>\nstatic const union { uint16_t align; uint8_t data[1056]; } proch_font = { .data = {\n'
    font_header += ','.join(str(b) for b in atlas) + '\n}};\n'
    font_header += '#define proch_font_mask proch_font\n'
    font_header += '#define PROCH_FONT_SAMPLE ' + literal('Mikołaj / Konstancja: '+' '.join(POLISH)) + '\n'
    (directory/'font.h').write_text(font_header)
    header = '/* Generated labels, encoded for the PROCH font. */\n'
    scenes = json.loads((ROOT/'scenes.json').read_text())
    items = json.loads((ROOT/'items.json').read_text())
    quests = json.loads((ROOT/'quests.json').read_text())
    for name, source, field in [('scene_names',scenes,'name'),('item_names',items,'name'),('quest_names',quests,'title')]:
        header += f'static const char *const {name}[] = {{"",\n'
        header += ',\n'.join(literal(row[field]) for row in source) + '\n};\n'
    (directory/'content.h').write_text(header)
    (directory/'font.pbm').write_bytes(b'P4\n96 88\n'+atlas)
    (directory/'font-mask.pbm').write_bytes(b'P4\n96 88\n'+atlas)


if __name__ == '__main__':
    generate(sys.argv[1] if len(sys.argv)>1 else ROOT/'build/generated')
